"""
Animated Buddy - reads animations composed of STEPS
======================================================
Each animation in animations.json (generated by organizer.py v3) is a list
of "steps". Each step is one of two cases:

- {"mode": "alone", "file": "body.png"}
    -> shows that frame in isolation, nothing overlaid.

- {"mode": "combined", "file": "body.png", "extra_file": "mouth.png",
   "offset_x": 120, "offset_y": 80}
    -> shows "file" (the base) with "extra_file" (e.g. the mouth) drawn on
       top, at the position given by the offset.

This lets a single animation mix moments where the body stays still alone
(pauses) with moments where the body appears combined with an overlaid
mouth (talking) - without having to duplicate the whole body in every
talking frame.

Each animation also carries a free-text "description" from the JSON, used
here just to print to the console when switching animations - handy for
debugging/understanding what each state represents, and you can reuse that
text elsewhere in your assistant (e.g. logging).
"""
