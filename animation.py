    # ------------------------------------------------------------------
    # Assistant control (states <-> animations)
    # ------------------------------------------------------------------
    def _play_state(self, name):
        if name in self.ready_frames:
            self.play_animation(name, next_after_finish=name)

    def _schedule_next_idle_gesture(self):
        interval_ms = random.randint(4000, 9000)
        QTimer.singleShot(interval_ms, self._idle_gesture_tick)

    def _idle_gesture_tick(self):
        if self.current_state != "IDLE":
            return
        gesture = random.choice(states.IDLE_GESTURES)
        self.play_animation(
            gesture,
            next_after_finish=states.IDLE_BASE,
            once=True,
            on_finish_callback=self._schedule_next_idle_gesture,
        )

    def enter_state(self, state, text=None):
        self.current_state = state

        if state == "IDLE":
            self._hide_bubble()
            self._play_state(states.IDLE_BASE)
            self._schedule_next_idle_gesture()

        elif state == "GREETING":
            self._play_state(random.choice(states.GREETING_POOL))
            QTimer.singleShot(3000, self._on_greeting_finished)

        elif state == "LISTENING":
            self._hide_bubble()
            self._play_state(random.choice(states.LISTENING_POOL))

        elif state == "THINKING":
            self._play_state(random.choice(states.THINKING_POOL))

        elif state == "TALKING":
            pool = states.choose_pool_for_reply(text)
            self._play_state(random.choice(pool))
            self._show_bubble_text(text)
            if self.voice.muted:
                duration_ms = max(1500, int(len(text or "") * 55))
                QTimer.singleShot(duration_ms, self._on_speech_finished)
            else:
                self.voice.speak(text)

    def process_question(self, text):
        text = (text or "").strip()
        if not text:
            return
        self.enter_state("THINKING")
        self._worker = AskWorker(self.brain, text)
        self._worker.result.connect(lambda r: self.enter_state("TALKING", text=r))
        self._worker.error.connect(self._on_reply_error)
        self._worker.start()

    def _on_reply_error(self, technical_message):
        print(f"[error talking to the AI] {technical_message}")
        self.enter_state("TALKING", text="Deu erro ao pensar - o Ollama tá rodando? (veja o console)")

    def _on_transcription(self, text):
        text = (text or "").strip()
        if not text:
            self.enter_state("TALKING", text="Não te ouvi direito, tenta de novo?")
            return
        self.process_question(text)

    def _on_greeting_finished(self):
        if self.current_state == "GREETING":
            self.enter_state("IDLE")

    def _on_speech_finished(self):
        if self.current_state == "TALKING":
            self.enter_state("IDLE")

    # ------------------------------------------------------------------
    # Proactive Todoist reminders
    # ------------------------------------------------------------------
    def _check_todoist_reminders(self):
        self._reminder_worker = TodoistCheckWorker(self.todoist)
        self._reminder_worker.result.connect(self._on_todoist_check_result)
        self._reminder_worker.error.connect(lambda e: print(f"[todoist reminder check failed] {e}"))
        self._reminder_worker.start()

    def _on_todoist_check_result(self, tasks):
        if self.current_state != "IDLE":
            return  # try again on the next poll instead of interrupting
        new_tasks = [t for t in tasks if t["id"] not in self._reminded_task_ids]
        if not new_tasks:
            return
        for task in new_tasks:
            self._reminded_task_ids.add(task["id"])

        if len(new_tasks) == 1:
            text = f"Lembrete: você tem a tarefa \"{new_tasks[0]['content']}\" pra fazer."
        else:
            items = ", ".join(task["content"] for task in new_tasks[:5])
            text = f"Lembrete: você tem {len(new_tasks)} tarefas pendentes: {items}."
        self.enter_state("TALKING", text=text)

    # ------------------------------------------------------------------
    # Proactive Google Calendar reminders
    # ------------------------------------------------------------------
    def _check_calendar_reminders(self):
        self._calendar_worker = CalendarCheckWorker(self.calendar)
        self._calendar_worker.result.connect(self._on_calendar_check_result)
        self._calendar_worker.error.connect(lambda e: print(f"[calendar reminder check failed] {e}"))
        self._calendar_worker.start()

    def _on_calendar_check_result(self, events):
        if self.current_state != "IDLE":
            return  # try again on the next poll instead of interrupting

        soon_cutoff = datetime.datetime.now().astimezone() + datetime.timedelta(minutes=CALENDAR_LOOKAHEAD_MINUTES)
        upcoming_soon = []
        for event in events:
            if event["id"] in self._reminded_event_ids or not event.get("start"):
                continue
            try:
                start = datetime.datetime.fromisoformat(event["start"])
            except ValueError:
                continue
            if start.tzinfo is None:
                start = start.astimezone()
            if start <= soon_cutoff:
                upcoming_soon.append(event)

        if not upcoming_soon:
            return
        for event in upcoming_soon:
            self._reminded_event_ids.add(event["id"])

        if len(upcoming_soon) == 1:
            text = f"Lembrete: você tem \"{upcoming_soon[0]['summary']}\" daqui a pouco."
        else:
            items = ", ".join(event["summary"] for event in upcoming_soon[:5])
            text = f"Lembrete: você tem {len(upcoming_soon)} eventos chegando: {items}."
        self.enter_state("TALKING", text=text)

    # ------------------------------------------------------------------
    # Proactive language learning tips (German)
    # ------------------------------------------------------------------
    def _schedule_next_language_tip(self):
        interval_ms = random.randint(LANGUAGE_TIP_MIN_INTERVAL_MS, LANGUAGE_TIP_MAX_INTERVAL_MS)
        QTimer.singleShot(interval_ms, self._language_tip_tick)

    def _language_tip_tick(self):
        if self.current_state != "IDLE":
            QTimer.singleShot(LANGUAGE_TIP_RETRY_INTERVAL_MS, self._language_tip_tick)
            return
        tip = random.choice(language_learning.GERMAN_TIPS)
        self.enter_state("TALKING", text=tip)
        self._schedule_next_language_tip()

    # ------------------------------------------------------------------
    # Claude Code notifications (see notify_claude_hook.py)
    # ------------------------------------------------------------------
    def _notify_queue_size(self):
        try:
            return os.path.getsize(NOTIFY_QUEUE_FILE)
        except OSError:
            return 0

    def _check_claude_notifications(self):
        if self.current_state != "IDLE":
            return  # try again on the next poll instead of interrupting
        size = self._notify_queue_size()
        if size <= self._notify_queue_offset:
            self._notify_queue_offset = size  # file was truncated/rotated
            return

        with open(NOTIFY_QUEUE_FILE, "r", encoding="utf-8") as f:
            f.seek(self._notify_queue_offset)
            new_lines = f.readlines()
        self._notify_queue_offset = size

        # Multiple events can pile up between polls (e.g. several quick
        # Stop hooks) - only the most recent one still worth announcing
        # gets spoken, the rest are just marked as read.
        now = time.time()
        latest_entry = None
        for line in new_lines:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if now - entry.get("ts", 0) <= NOTIFY_MAX_AGE_SECONDS:
                latest_entry = entry

        if latest_entry is None:
            return
        project = os.path.basename((latest_entry.get("cwd") or "").rstrip("/")) or "?"
        text = f"Claude ({project}): {latest_entry['message']}"
        self.enter_state("TALKING", text=text)

    # ------------------------------------------------------------------
    # Speech bubble (widgets inside the monkey's own window)
    # ------------------------------------------------------------------
    def _height_needed_for_text(self, text, width):
        padding_margin = 20  # ~ stylesheet padding (8px each side) + slack
        fm = QFontMetrics(self.bubble_label.font())
        rect = fm.boundingRect(0, 0, width - padding_margin, 0, Qt.TextWordWrap, text)
        return rect.height() + padding_margin

    def _adjust_bubble_height(self, new_bubble_height):
        """Resizes the bubble area (and the whole window) while keeping the
        monkey anchored in the same screen spot - the window grows UPWARD."""
        delta = new_bubble_height - self._current_bubble_height
        if delta == 0:
            return
        sprite_width, sprite_height = self.canvas_size
        sprite_x = (self._window_width - sprite_width) // 2

        self.setGeometry(self.x(), self.y() - delta, self._window_width, sprite_height + new_bubble_height)
        self.label.setGeometry(sprite_x, new_bubble_height, sprite_width, sprite_height)
        self.bubble_label.setGeometry(0, 0, self._window_width, new_bubble_height - 12)
        self.bubble_input.setGeometry(0, 0, self._window_width, new_bubble_height - 12)
        self._current_bubble_height = new_bubble_height

    def _show_bubble_text(self, text):
        self.bubble_input.hide()
        needed_height = self._height_needed_for_text(text, self._window_width)
        bubble_height = max(BUBBLE_HEIGHT, min(needed_height + 12, BUBBLE_HEIGHT_MAX))
        self._adjust_bubble_height(bubble_height)
        self.bubble_label.setText(text)
        self.bubble_label.show()

    def _hide_bubble(self):
        self.bubble_label.hide()
        self.bubble_input.hide()
        self._adjust_bubble_height(BUBBLE_HEIGHT)

    def _toggle_bubble_input(self):
        if self.bubble_input.isVisible():
            self._hide_bubble()
        else:
            self.bubble_label.hide()
            self._adjust_bubble_height(BUBBLE_HEIGHT)
            self.bubble_input.show()
            self.bubble_input.setFocus()

    def _send_from_input(self):
        text = self.bubble_input.text().strip()
        self.bubble_input.clear()
        self.bubble_input.hide()
        if text:
            self.process_question(text)

    # ------------------------------------------------------------------
    # Loading and pre-processing
    # ------------------------------------------------------------------
    def load_definitions(self):
        if not os.path.exists(ANIMATIONS_FILE):
            print(f"Warning: {ANIMATIONS_FILE} not found.")
            return {}
        with open(ANIMATIONS_FILE, "r", encoding="utf-8") as f:
            return json.load(f)

    def get_file_pixmap(self, file_name):
        if file_name in self.file_pixmap_cache:
            return self.file_pixmap_cache[file_name]
        path = os.path.join(IMAGES_FOLDER, file_name)
        if not os.path.exists(path):
            print(f"Error: file not found {path}")
            return None
        pm = remove_background(path)
        self.file_pixmap_cache[file_name] = pm
        return pm

    def compose_step(self, step):
        """Converts a JSON step ('alone' or 'combined') into a single,
        ready-to-display QPixmap, supporting up to 3 layers."""
        if step["mode"] == "alone":
            return self.get_file_pixmap(step["file"])

        base_pm = self.get_file_pixmap(step["file"])
        if base_pm is None:
            return None
        composed = QPixmap(base_pm.size())
        composed.fill(Qt.transparent)
        painter = QPainter(composed)
        painter.drawPixmap(0, 0, base_pm)

        # Layer 2 (e.g. mailbox)
        overlay_pm = self.get_file_pixmap(step.get("extra_file"))
        if overlay_pm is not None:
            painter.drawPixmap(step.get("offset_x", 0), step.get("offset_y", 0), overlay_pm)

        # Layer 3 (e.g. eyes/glance cutout)
        if "extra_file2" in step:
            overlay_pm2 = self.get_file_pixmap(step.get("extra_file2"))
            if overlay_pm2 is not None:
                painter.drawPixmap(step.get("offset_x2", 0), step.get("offset_y2", 0), overlay_pm2)

        painter.end()
        return composed

    def prepare_all_frames(self):
        for name, data in self.animation_definitions.items():
            description = data.get("description", "")
            if description:
                print(f"[animation '{name}'] {description}")

            frames = []
            for step in data.get("steps", []):
                pm = self.compose_step(step)
                if pm is not None:
                    frames.append(pm)
            self.ready_frames[name] = frames

    def calculate_canvas_size(self):
        max_width, max_height = 100, 100
        for frames in self.ready_frames.values():
            for pm in frames:
                max_width = max(max_width, pm.width())
                max_height = max(max_height, pm.height())
        return max_width, max_height

    # ------------------------------------------------------------------
    # Playback (with smooth transitions between frames/animations)
    # ------------------------------------------------------------------
    def _pixmap_on_canvas(self, sprite_pixmap):
        canvas = QPixmap(*self.canvas_size)
        canvas.fill(Qt.transparent)
        painter = QPainter(canvas)
        x = (self.canvas_size[0] - sprite_pixmap.width()) // 2
        y = self.canvas_size[1] - sprite_pixmap.height()
        painter.drawPixmap(x, max(y, 0), sprite_pixmap)
        painter.end()
        return canvas

    def _blend_pixmaps(self, pm_from, pm_to, fraction_to):
        """Combines two frames (already at canvas size) by opacity, to
        create a smooth transition instead of a hard cut between poses."""
        if pm_from is None:
            return pm_to
        result = QPixmap(pm_to.size())
        result.fill(Qt.transparent)
        painter = QPainter(result)
        painter.drawPixmap(0, 0, pm_from)
        painter.setOpacity(max(0.0, min(1.0, fraction_to)))
        painter.drawPixmap(0, 0, pm_to)
        painter.end()
        return result

    def play_animation(self, name, next_after_finish=None, once=False, on_finish_callback=None):
        """Switches the animation being shown, always with a short
        transition from whatever was on screen (avoids a hard "jump"
        between poses). With once=True, plays only a single pass (ignoring
        the JSON's loop flag) and moves on to next_after_finish - used for
        one-shot gestures (blink, yawn) that shouldn't keep repeating
        forever. on_finish_callback is an optional callback fired when this
        pass actually finishes (handy to only schedule the next gesture
        after the current one truly ended, instead of on a fixed interval
        that could interrupt it midway)."""
        if name not in self.ready_frames or not self.ready_frames[name]:
            print(f"Animation '{name}' doesn't exist (or is empty) in {ANIMATIONS_FILE}.")
            return

        target = self._pixmap_on_canvas(self.ready_frames[name][0])

        self.current_animation = name
        self.frame_index = 0
        self.next_animation_after_finish = next_after_finish
        self.force_once = once
        self._on_finish_callback = on_finish_callback

        if self._pm_next is not None:
            self._pm_previous = self._pm_next
            self._segment_duration = SWITCH_TRANSITION_DURATION
        else:
            self._pm_previous = target
            self._segment_duration = 0.0
        self._pm_next = target
        self._segment_start = time.monotonic()

    def current_animation_description(self):
        """Returns the description text of the animation currently playing
        (handy if you want to show/log what the buddy is doing right now)."""
        if not self.current_animation:
            return ""
        return self.animation_definitions.get(self.current_animation, {}).get("description", "")

    def _render_tick(self):
        """Runs at ~30fps, independent of each animation's fps: interpolates
        between the previous and next frame to smooth out the motion."""
        if self._pm_next is None:
            return
        now = time.monotonic()
        fraction = 1.0 if self._segment_duration <= 0 else (now - self._segment_start) / self._segment_duration

        if fraction >= 1.0:
            self.label.setPixmap(self._pm_next)
            self._advance_frame()
        else:
            self.label.setPixmap(self._blend_pixmaps(self._pm_previous, self._pm_next, fraction))

    def _advance_frame(self):
        data = self.animation_definitions[self.current_animation]
        frames = self.ready_frames[self.current_animation]
        total_frames = len(frames)
        fps = data.get("fps", 8)
        next_index = self.frame_index + 1

        if next_index >= total_frames:
            if data.get("loop", True) and not self.force_once:
                next_index = 0
            else:
                next_animation = self.next_animation_after_finish
                callback = self._on_finish_callback
                self._on_finish_callback = None
                if next_animation and next_animation in self.ready_frames:
                    self.play_animation(next_animation)
                if callback:
                    callback()
                return

        self.frame_index = next_index
        self._pm_previous = self._pm_next
        self._pm_next = self._pixmap_on_canvas(frames[self.frame_index])
        self._segment_duration = 1.0 / fps
        self._segment_start = time.monotonic()

    # ------------------------------------------------------------------
    def mousePressEvent(self, event):
        if event.button() == Qt.LeftButton:
            self.drag_position = event.globalPos() - self.frameGeometry().topLeft()
            self._dragged = False
            event.accept()

    def mouseMoveEvent(self, event):
        if event.buttons() == Qt.LeftButton:
            self._dragged = True
            self.move(event.globalPos() - self.drag_position)
            event.accept()

    def mouseReleaseEvent(self, event):
        if event.button() == Qt.LeftButton and not self._dragged:
            self._toggle_bubble_input()
        event.accept()

    def mouseDoubleClickEvent(self, event):
        """Double-click makes the monkey wave hello on demand."""
        self.enter_state("GREETING")

    def contextMenuEvent(self, event):
        menu = QMenu(self)
        mute_action = menu.addAction("Mute voice")
        mute_action.setCheckable(True)
        mute_action.setChecked(self.voice.muted)
        menu.addAction("Push-to-talk: hold F9 to talk").setEnabled(False)
        menu.addSeparator()
        quit_action = menu.addAction("Quit")

        chosen = menu.exec_(event.globalPos())
        if chosen == mute_action:
            self.voice.muted = not self.voice.muted
        elif chosen == quit_action:
            QApplication.instance().quit()


