def remove_background(image_path, background_color=BACKGROUND_COLOR, tolerance=TOLERANCE):
    """Loads an image and returns a QPixmap with the background made
    transparent, using a tolerance band instead of an exact binary mask.
    Vectorized with numpy - the pure-Python pixel-by-pixel version took
    minutes to prepare all the frames for ~50 animations."""
    image = QImage(image_path)
    if image.isNull():
        return None
    image = image.convertToFormat(QImage.Format_ARGB32)

    width, height = image.width(), image.height()
    bytes_per_line = image.bytesPerLine()
    pointer = image.bits()
    pointer.setsize(bytes_per_line * height)
    raw = np.frombuffer(pointer, dtype=np.uint8).reshape((height, bytes_per_line))
    pixels = raw[:, : width * 4].reshape((height, width, 4)).copy()

    # Format_ARGB32 stores each pixel in memory (little-endian) as B, G, R, A
    b, g, r = pixels[..., 0].astype(np.int16), pixels[..., 1].astype(np.int16), pixels[..., 2].astype(np.int16)
    r0, g0, b0 = background_color
    mask = (
        (np.abs(r - r0) <= tolerance)
        & (np.abs(g - g0) <= tolerance)
        & (np.abs(b - b0) <= tolerance)
    )
    pixels[mask] = 0

    result = QImage(pixels.tobytes(), width, height, width * 4, QImage.Format_ARGB32)
    return QPixmap.fromImage(result.copy())


class AskWorker(QThread):
    """Runs OllamaBrain.ask() off the UI thread so the animations don't
    freeze while the model is thinking."""
    result = pyqtSignal(str)
    error = pyqtSignal(str)

    def __init__(self, brain, text):
        super().__init__()
        self.brain = brain
        self.text = text

    def run(self):
        try:
            reply = self.brain.ask(self.text)
            self.result.emit(reply)
        except Exception as error:
            self.error.emit(str(error))


class TodoistCheckWorker(QThread):
    """Polls Todoist for due/overdue tasks off the UI thread."""
    result = pyqtSignal(list)
    error = pyqtSignal(str)

    def __init__(self, todoist_client):
        super().__init__()
        self.todoist_client = todoist_client

    def run(self):
        try:
            tasks = self.todoist_client.list_tasks(when="today_or_overdue")
            self.result.emit(tasks)
        except Exception as error:
            self.error.emit(str(error))


class CalendarCheckWorker(QThread):
    """Polls Google Calendar for events starting soon, off the UI thread."""
    result = pyqtSignal(list)
    error = pyqtSignal(str)

    def __init__(self, calendar_client):
        super().__init__()
        self.calendar_client = calendar_client

    def run(self):
        try:
            events = self.calendar_client.list_events(when="upcoming")
            self.result.emit(events)
        except Exception as error:
            self.error.emit(str(error))


class AnimatedBuddy(QMainWindow):
    def __init__(self):
        super().__init__()

        self.setWindowFlags(Qt.FramelessWindowHint | Qt.WindowStaysOnTopHint | Qt.SubWindow)
        self.setAttribute(Qt.WA_TranslucentBackground)

        self.label = QLabel(self)

        self.animation_definitions = self.load_definitions()
        self.file_pixmap_cache = {}   # file_name -> QPixmap with background removed
        self.ready_frames = {}        # animation_name -> [QPixmap, QPixmap, ...]

        self.prepare_all_frames()

        self.current_animation = None
        self.frame_index = 0
        self.next_animation_after_finish = None
        self.force_once = False
        self._on_finish_callback = None

        self._pm_previous = None
        self._pm_next = None
        self._segment_start = 0.0
        self._segment_duration = 0.0

        self.timer = QTimer(self)
        self.timer.timeout.connect(self._render_tick)
        self.timer.start(30)  # ~33fps of interpolation, independent of each animation's fps

        self.canvas_size = self.calculate_canvas_size()
        sprite_width, sprite_height = self.canvas_size
        self._window_width = max(sprite_width, BUBBLE_WIDTH)
        self._current_bubble_height = BUBBLE_HEIGHT
        window_height = sprite_height + BUBBLE_HEIGHT
        self.setGeometry(100, 100, self._window_width, window_height)

        sprite_x = (self._window_width - sprite_width) // 2
        self.label.setGeometry(sprite_x, BUBBLE_HEIGHT, sprite_width, sprite_height)

        # Speech bubble: widgets that are children of the SAME window as the
        # monkey (instead of a separate top-level window) - an independent
        # frameless+translucent QWidget turned out to be unreliable to
        # composite on this machine (it would sometimes just not paint).
        bubble_style = (
            "background-color: rgba(255, 255, 255, 235); border-radius: 10px;"
            "padding: 8px; font-size: 13px; color: #222;"
        )

        self.bubble_label = QLabel(self)
        self.bubble_label.setGeometry(0, 0, self._window_width, BUBBLE_HEIGHT - 12)
        self.bubble_label.setWordWrap(True)
        self.bubble_label.setAlignment(Qt.AlignCenter)
        self.bubble_label.setStyleSheet(bubble_style)
        self.bubble_label.hide()

        self.bubble_input = QLineEdit(self)
        self.bubble_input.setGeometry(0, 0, self._window_width, BUBBLE_HEIGHT - 12)
        self.bubble_input.setPlaceholderText("Talk to the monkey...")
        self.bubble_input.setStyleSheet(bubble_style)
        self.bubble_input.returnPressed.connect(self._send_from_input)
        self.bubble_input.hide()

        self.drag_position = QPoint()
        self._dragged = False

        # ---------------- Assistant behavior ----------------
        self.current_state = "IDLE"
        self._worker = None

        self.todoist = TodoistClient()
        self.google_auth = GoogleOAuthClient()  # shared login for Calendar + Gmail
        self.calendar = GoogleCalendarClient(auth=self.google_auth)
        self.gmail = GmailClient(auth=self.google_auth)
        self.brain = OllamaBrain(
            tools={
                "list_tasks": {"schema": LIST_TASKS_SCHEMA, "function": self.todoist.list_tasks},
                "add_task": {"schema": ADD_TASK_SCHEMA, "function": self.todoist.add_task},
                "move_task_to_project": {"schema": MOVE_TASK_SCHEMA, "function": self.todoist.move_task_to_project},
                "list_events": {"schema": LIST_EVENTS_SCHEMA, "function": self.calendar.list_events},
                "create_event": {"schema": CREATE_EVENT_SCHEMA, "function": self.calendar.create_event},
                "list_recent_emails": {"schema": LIST_RECENT_EMAILS_SCHEMA, "function": self.gmail.list_recent_emails},
                "search_emails": {"schema": SEARCH_EMAILS_SCHEMA, "function": self.gmail.search_emails},
                "read_email": {"schema": READ_EMAIL_SCHEMA, "function": self.gmail.read_email},
            },
            tool_trigger_keywords=TODOIST_KEYWORDS + CALENDAR_KEYWORDS + GMAIL_KEYWORDS,
        )
        self.voice = VoiceAssistant()

        self.voice.recording_started.connect(lambda: self.enter_state("LISTENING"))
        self.voice.transcription_ready.connect(self._on_transcription)
        self.voice.speech_finished.connect(self._on_speech_finished)

        self._reminded_task_ids = set()
        self._reminder_worker = None
        self._reminder_timer = QTimer(self)
        self._reminder_timer.timeout.connect(self._check_todoist_reminders)
